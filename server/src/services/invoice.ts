import PDFDocument from "pdfkit";
import { prisma } from "../db";
import { proofHash } from "../utils/codes";

// Invoice numbering: JAR-1001, JAR-1002, … (sequential, never reused).
// Dev implementation: count + 1001 inside a transaction. Safe for a
// single-instance server. For multi-instance prod, replace with a DB
// sequence / locked counter row (see Copilot Prompt 6).
export async function nextInvoiceNumber(): Promise<string> {
  const count = await prisma.invoice.count();
  return `JAR-${1001 + count}`;
}

export interface ReceiptData {
  number: string;
  portalName: string;
  payerEmail: string;
  payerName?: string | null;
  amount: string;
  currency: string;
  status: string;
  items: Array<{ description: string; amount: string }>;
  methodLabel?: string | null;
  methodType?: string | null;
  reference?: string | null;
  proofHash?: string | null;
  barcodePayload?: string | null;
  createdAt: Date;
  paidAt?: Date | null;
}

/** Build the proof hash for a completed payment. */
export function buildProofHash(invoiceNumber: string, amount: string, currency: string, reference: string, paidAtIso: string): string {
  return proofHash(`${invoiceNumber}|${amount}|${currency}|${reference}|${paidAtIso}`);
}

/** Generate the receipt PDF. Returns a Buffer. */
export function generateReceiptPdf(data: ReceiptData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(20).text("INVOICE RECEIPT", { align: "left" });
    doc.moveDown(0.25);
    doc.fontSize(12).text(data.portalName);
    doc.fontSize(10).fillColor("#555").text(`Invoice ${data.number}  •  ${data.createdAt.toISOString()}`);
    doc.fillColor("#000").moveDown();

    doc.fontSize(11).text(`Billed to: ${data.payerName ? `${data.payerName} ` : ""}<${data.payerEmail}>`);
    doc.text(`Status: ${data.status}${data.paidAt ? `  •  Paid ${data.paidAt.toISOString()}` : ""}`);
    doc.moveDown();

    doc.fontSize(11).text("Items", { underline: true });
    for (const item of data.items) {
      doc.text(`${item.description} — ${item.amount} ${data.currency}`);
    }
    doc.moveDown(0.5);
    doc.fontSize(13).text(`Total: ${data.amount} ${data.currency}`);
    doc.moveDown();

    if (data.methodLabel) doc.fontSize(11).text(`Payment method: ${data.methodLabel}${data.methodType ? ` (${data.methodType})` : ""}`);
    if (data.reference) doc.text(`Transaction reference: ${data.reference}`);
    if (data.proofHash) doc.text(`Proof of payment: ${data.proofHash}`);
    if (data.barcodePayload) doc.text(`Barcode: ${data.barcodePayload}`);
    doc.moveDown();
    doc.fontSize(9).fillColor("#555").text("Proof of payment — verify with the proof hash above. Generated by JARVIS.");
    doc.end();
  });
}
